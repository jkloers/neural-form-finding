#!/usr/bin/env bash
# Build the defense deck: stage the figures, compile twice, then report anything that will
# show on the screen as a clipped or missing element.
#
#   bash slides/build.sh            the deck
#   bash slides/build.sh notes      the deck plus a speaker-notes twin
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
repo="$(cd "$here/.." && pwd)"
cd "$here"

mkdir -p figures

# ── Stage the plates ───────────────────────────────────────────────────────────────────────
# Copied rather than symlinked: paper/ is Overleaf-synced and can be replaced under us mid
# build, and a dangling symlink fails as a missing file three hundred lines into the log.
stage() {  # stage <src> <dest-name>
  if [ -f "$repo/$1" ]; then
    cp -f "$repo/$1" "figures/$2"
  else
    echo "MISSING SOURCE: $1" >&2
  fi
}

stage paper/Images/shield_pipeline.pdf        shield_pipeline.pdf
stage paper/Images/energy_landscape.pdf       energy_landscape.pdf
stage paper/Images/hinge_path_design.pdf      hinge_path_design.pdf
# Staged for its panel (a) ONLY, which the parametrization slide crops out with trim/clip.
# The whole plate is still never shown: see the note below.
stage paper/Images/pipeline_overview.pdf      pipeline_overview.pdf

# NOT staged from paper/Images, deliberately:
#
#   deployment_validation.pdf, hinge_buckle.pdf   The manuscript merged the two into one
#     full-page plate, fig:physical-validation, and stopped emitting them. Their PDFs are still on
#     disk, so a stage() of either SUCCEEDS and silently serves a retired figure: the copies left
#     there predate the unmirroring, the squaring of the taped target and the 500 mm bar. All
#     three slides that show this content cut rows out of the merged plate instead.
#
#   pipeline_overview.pdf, AS A WHOLE PLATE   Nearly square, 437 x 425 bp. A 16:9 body is
#     410 x 188 pt, so the figure is height-limited there and prints half the slide wide, at 47
#     per cent of the type size it was authored for. The deck shows the same five cards in ONE
#     ROW as pipeline_row.pdf, built by the plate's own generator under --slide and authored at
#     408 bp, so an authored point size is a projected one. Its panel (a) alone is ALSO shown, on
#     the parametrization slide, cropped from the page plate staged above: that card is 116.4 x
#     179.8 bp, so on its own it prints at about 105 per cent of its authored size.
#
#   validity_ladder, hinge_layout, path_dependence, taylor_convergence, surrogate_validity,
#     solution_set   All six carry print furniture: panel letters, and in four cases a rule drawn
#     round the plate. On a page those do real work, because running prose says "see (b)" and
#     nothing else can group four columns. A slide has a speaker for both. The deck shows
#     <name>_slide.pdf for each, built by slides/make_slide_figures.sh under NFF_SLIDE_FIGURES=1
#     and, where it applies, --no-boxes. The paper's own copies here are untouched.
#     ⚠ A stage() of any of the six SUCCEEDS and silently serves the lettered page figure.
#
#   notation_map.pdf   Not shown at all any more. The slide that carried the whole chain and every
#     variable in it was cut: it was the densest frame in the deck and the pipeline row already
#     carries the structure. The --slide composition is still in plot_notation_map.py.
#
#   katagami_leaves.pdf   Our own drawing of a komon pattern. The opening slide shows carved
#     stencils by their own makers instead, so nothing here reads as a historical artefact that
#     was in fact generated by this work.

# Slide-aspect recuts and slide-only plates, produced by slides/make_slide_figures.sh
for f in matrix_all.pdf two_scales_ligament.png pipeline_row.pdf \
         two_scales_question.pdf physical_validation_slide.pdf sheet_closed_photo.png \
         validity_ladder_slide.pdf hinge_layout_slide.pdf path_dependence_slide.pdf \
         taylor_convergence_slide.pdf surrogate_validity_slide.pdf solution_set_slide.pdf \
         matrix_detail.pdf kinematic_pair.pdf pipeline_row_kin.pdf design_thumb_1.png; do
  [ -f "figures/$f" ] || echo "NOT YET BUILT: figures/$f  (run slides/make_slide_figures.sh)" >&2
done

# ── Compile ────────────────────────────────────────────────────────────────────────────────
compile() {
  xelatex -interaction=nonstopmode -halt-on-error pfe_defense.tex >/dev/null 2>&1 || {
    echo "--- BUILD FAILED ---"
    xelatex -interaction=nonstopmode pfe_defense.tex 2>&1 | grep -A6 "^!" | head -40
    exit 1
  }
}

# Twice: the table of contents and \insertsectionhead in the footer both need the .aux from a
# previous run, so a single pass leaves the outline empty and the footer blank on every slide.
compile
compile

# ── Report ─────────────────────────────────────────────────────────────────────────────────
echo
echo "=== pages ==="
# From the file, not from Spotlight: mdls reports (null) on a PDF written seconds ago.
pdfinfo pfe_defense.pdf 2>/dev/null | awk '/^Pages:/{print $2}' \
  || grep -c '^\\shipout' pfe_defense.log 2>/dev/null || echo "?"
echo
echo "=== overfull boxes (ink that will be clipped on screen) ==="
grep -c "Overfull" pfe_defense.log || echo 0
grep "Overfull" pfe_defense.log | head -20 || true
echo
echo "=== undefined references / missing files ==="
grep -iE "undefined (reference|control)|File .* not found|LaTeX Warning: Reference" pfe_defense.log | head -20 || true
echo
echo "built: $here/pfe_defense.pdf"
